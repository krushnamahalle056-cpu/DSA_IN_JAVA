package array;

public class QueForLoop {
    public class Main {
        public static void main(String[] args) {
            for(int i = 1; i <= 20; i++) {
                System.out.println(i);
            }

            // Print 20 to 1
            for(int i = 20; i >= 1; i--) {
                System.out.println(i);
            }

            // Print even numbers 1 to 50

        }
    }
}
